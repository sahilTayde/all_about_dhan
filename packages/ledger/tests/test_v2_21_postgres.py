def test_migrate_failure_does_not_record_version(tmp_path: Path) -> None:
    db = tmp_path / "aad.sqlite"
    migrate(db)
    bad = tmp_path / "099_bad.sql"
    bad.write_text("CREATE TABLE broken (id INTEGER PRIMARY KEY);\nTHIS IS NOT SQL;\n", encoding="utf-8")
    from ledger.migrate import list_migration_files, version_of

    files = [*list_migration_files(), bad]
    with pytest.raises(Exception):
        migrate(db, files=files)
    store = SqliteLedgerStore(db)
    assert store.schema_version < version_of(bad) or store.schema_version == CODE_SCHEMA_VERSION
    assert store.schema_version == CODE_SCHEMA_VERSION
    store.close()


