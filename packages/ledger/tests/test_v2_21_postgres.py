"""V2-21: STATE_DSN, fail-closed migrations, health ping, export checksums, dual-engine."""

from __future__ import annotations

import os
import re
from datetime import datetime
from pathlib import Path

import pytest

from ledger import SchemaTooNew, SqliteLedgerStore, StoreConfigError, load_store_config, migrate
from ledger.export import checksum_lines, row_line
from ledger.migrate import CODE_SCHEMA_VERSION, list_dialect_files, list_migration_files
from ledger.postgres import is_postgres_dsn, redact_dsn, rewrite_sql_for_postgres, split_sql

REPO = Path(__file__).resolve().parents[3]
NOW = datetime.fromisoformat("2026-09-28T10:00:00+05:30")
DROP_COL = re.compile(r"\bDROP\s+COLUMN\b|\bRENAME\s+COLUMN\b", re.IGNORECASE)


def _pg_dsn() -> str:
    return (os.environ.get("STATE_DSN") or "").strip()


def _require_pg() -> str:
    dsn = _pg_dsn()
    if not dsn or not is_postgres_dsn(dsn):
        pytest.skip("STATE_DSN unset (sqlite-only unit job)")
    pytest.importorskip("psycopg")
    return dsn


def _reset_pg(dsn: str) -> None:
    from ledger.postgres import connect_postgres

    conn = connect_postgres(dsn)
    try:
        conn.execute("DROP SCHEMA public CASCADE")
        conn.execute("CREATE SCHEMA public")
    finally:
        conn.close()


def _envelope() -> object:
    from types import SimpleNamespace

    return SimpleNamespace(
        event_id="evt_v221",
        stream="md:clock",
        event_type="CLOCK",
        available_ts=NOW.isoformat(),
        payload={"seq": 1},
    )


def test_shared_migrations_exclude_dialect_files() -> None:
    names = [f.name for f in list_migration_files()]
    assert names == ["001_core.sql", "002_v2_core.sql", "003_entry_plan_payload.sql"]
    dialect = [f.name for f in list_dialect_files("pg")]
    assert "002_v2_core.pg.sql" in dialect
    assert all(not n.endswith(".pg.sql") for n in names)


def test_migrations_expand_contract_only() -> None:
    for path in list_migration_files():
        text = path.read_text(encoding="utf-8")
        assert DROP_COL.search(text) is None, path.name


def test_rewrite_autoincrement_and_split_dollar_quotes() -> None:
    sql = "id INTEGER PRIMARY KEY AUTOINCREMENT"
    assert "GENERATED BY DEFAULT AS IDENTITY" in rewrite_sql_for_postgres(sql)
    assert "CREATE OR REPLACE VIEW" in rewrite_sql_for_postgres("CREATE VIEW IF NOT EXISTS daily_pnl AS SELECT 1")
    body = "CREATE FUNCTION f() RETURNS trigger AS $$ BEGIN RAISE EXCEPTION 'x'; END; $$ LANGUAGE plpgsql;"
    parts = split_sql(body)
    assert len(parts) == 1 and "RAISE EXCEPTION" in parts[0]


