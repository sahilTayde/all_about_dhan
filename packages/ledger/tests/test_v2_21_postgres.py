def test_dual_engine_checkpoint_outbox_positions() -> None:
    dsn = _require_pg()
    from ledger.postgres import PostgresLedgerStore

    _reset_pg(dsn)
    store = PostgresLedgerStore(dsn, migrate_schema=True)
    try:
        ping = store.health_ping()
        assert ping["ok"] is True and ping["engine"] == "postgres"
        assert ping["schema_version"] == CODE_SCHEMA_VERSION
        env = _envelope()
        with store.transaction():
            store.checkpoint(env)  # type: ignore[arg-type]
        assert store.get_last_checkpoint() is not None
        drained = store.drain_outbox()
        assert len(drained) == 1 and drained[0]["event_id"] == "evt_v221"
        assert store.drain_outbox() == []
        store.upsert_position_v2("founder", "NSE_FNO:NIFTY:2026-09-29:24400:CE", 65, "100.00", strategy_id="TEST")
        rows = store.positions_v2()
        assert int(rows[0]["net_qty"]) == 65 and rows[0]["strategy_id"] == "TEST"
    finally:
        store.close()


def test_postgres_refuses_newer_schema() -> None:
    dsn = _require_pg()
    from ledger.postgres import PostgresLedgerStore, connect_postgres

    _reset_pg(dsn)
    store = PostgresLedgerStore(dsn, migrate_schema=True)
    store.close()
    conn = connect_postgres(dsn)
    try:
        conn.execute("INSERT INTO schema_version (version, applied_at) VALUES (99, %s)", (NOW.isoformat(),))
    finally:
        conn.close()
    with pytest.raises(SchemaTooNew):
        PostgresLedgerStore(dsn)


def test_export_sqlite_to_postgres_checksums(tmp_path: Path) -> None:
    dsn = _require_pg()
    from ledger.export import export_sqlite_to_postgres

    db = tmp_path / "aad.sqlite"
    store = SqliteLedgerStore(db, migrate_schema=True)
    env = _envelope()
    with store.transaction():
        store.checkpoint(env)  # type: ignore[arg-type]
    store.upsert_position_v2("founder", "NSE_FNO:NIFTY:2026-09-29:24400:CE", 65, "100.00", strategy_id="TEST")
    store.close()
    _reset_pg(dsn)
    report = export_sqlite_to_postgres(db, dsn)
    assert report["ok"] is True
    assert report["tables"]["positions_v2"]["count"] == 1
    assert report["tables"]["engine_checkpoint"]["count"] == 1
    assert report["tables"]["outbox"]["count"] == 1
    with pytest.raises(Exception, match="refuse overwrite|already has"):
        export_sqlite_to_postgres(db, dsn)


